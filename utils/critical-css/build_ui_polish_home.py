"""Build css/ui-polish-home-critical.css: the css/ui-polish.css rules the home
page uses (ids in keep-ui-polish-home.txt). The header records the md5 of the
ui-polish.css it was cut from; inc/performance.php only uses the subset while
that still matches, so any later edit to ui-polish.css makes the home page load
the full file again until this is re-run. See README.md.

    python build_ui_polish_home.py ../../css/ui-polish.css ../../css/ui-polish-home-critical.css
"""
import gzip
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import cssparse

src = sys.argv[1]
tree = cssparse.load(src)
keep = {int(x) for x in open(os.path.join(HERE, 'keep-ui-polish-home.txt')).read().strip().split(',')}
css = cssparse.emit(tree, keep)
md5 = hashlib.md5(open(src, 'rb').read()).hexdigest()
header = ('/* css/ui-polish.css rules used by the home page; the full file loads after. '
          'Generated by utils/critical-css (ui-polish-home), see inc/performance.php. '
          'source-md5: ' + md5 + ' */')
open(sys.argv[2], 'w', encoding='utf8', newline='').write(header + css)
print('rules', len(keep), 'bytes', len(css), 'gz', len(gzip.compress(css.encode())), 'md5', md5)

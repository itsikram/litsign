import gzip
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import cssparse
tree = cssparse.load(sys.argv[1])
keep = {int(x) for x in open(os.path.join(HERE, 'keep-style-home.txt')).read().strip().split(',')}
css = cssparse.emit(tree, keep)
open(sys.argv[2], 'w', encoding='utf8', newline='').write('/* css/style.css rules used by the home page; the full file loads after. Generated by utils/critical-css (style-home), see inc/performance.php. */' + css)
print('rules', len(keep), 'bytes', len(css), 'gz', len(gzip.compress(css.encode())))
